#define OWL_BLOB(fn, bytes) \
    __asm__(".section .text.entry,\"ax\",@progbits\n.p2align 1\n" #fn ":\n  [--sp] = rets\n  call " #fn "_here\n" \
            "  pc = [sp++]\n" bytes "  .p2align 1\n" #fn "_here:\n  r0 = rets\n  rts\n"); \
    unsigned char *fn(void)
/* data address: name() + 2 (the 2-byte "pc = [sp++]" sits between the call and the data) */
#define OWL_BLOB_DATA(fn) (fn() + 2)
